CREATE DATABASE bd_red_donantes
    WITH ENCODING 'UTF8'
    TEMPLATE template0;


-- Conectarse a bd_red_donantes antes de ejecutar el resto del script.

CREATE SCHEMA IF NOT EXISTS banco_sangre;


-- fecha_ultima_donacion se actualiza en la misma transacción que la donación,
-- así la búsqueda de donantes aptos no necesita calcular MAX() sobre el historial.
CREATE TABLE IF NOT EXISTS banco_sangre.donante (
    id_donante BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cedula VARCHAR(16) NOT NULL,
    nombres VARCHAR(80) NOT NULL,
    apellidos VARCHAR(80) NOT NULL,
    sexo VARCHAR(1) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    tipo_sangre VARCHAR(3) NOT NULL,
    telefono VARCHAR(8) NOT NULL,
    correo VARCHAR(120),
    departamento VARCHAR(40) NOT NULL,
    direccion VARCHAR(200),
    fecha_ultima_donacion DATE,
    impedido_hasta DATE,
    motivo_impedimento VARCHAR(200),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro DATE NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT uq_donante_cedula
        UNIQUE (cedula),

    CONSTRAINT chk_donante_sexo
        CHECK (sexo IN ('M', 'F')),

    CONSTRAINT chk_donante_tipo_sangre
        CHECK (tipo_sangre IN ('O-', 'O+', 'A-', 'A+', 'B-', 'B+', 'AB-', 'AB+')),

    CONSTRAINT chk_donante_impedimento
        CHECK (impedido_hasta IS NULL OR motivo_impedimento IS NOT NULL)
);


CREATE TABLE IF NOT EXISTS banco_sangre.campania (
    id_campania BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    lugar VARCHAR(150) NOT NULL,
    departamento VARCHAR(40) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    meta_donantes INTEGER NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'Planificada',
    descripcion VARCHAR(300),

    CONSTRAINT chk_campania_fechas
        CHECK (fecha_fin >= fecha_inicio),

    CONSTRAINT chk_campania_meta
        CHECK (meta_donantes > 0),

    CONSTRAINT chk_campania_estado
        CHECK (estado IN ('Planificada', 'Activa', 'Finalizada', 'Cancelada'))
);


CREATE TABLE IF NOT EXISTS banco_sangre.hospital (
    id_hospital BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    departamento VARCHAR(40) NOT NULL,
    telefono VARCHAR(8),
    contacto VARCHAR(120),

    CONSTRAINT uq_hospital_nombre
        UNIQUE (nombre)
);


CREATE TABLE IF NOT EXISTS banco_sangre.solicitud (
    id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL,
    id_hospital BIGINT NOT NULL,
    fecha_solicitud DATE NOT NULL DEFAULT CURRENT_DATE,
    tipo_sangre VARCHAR(3) NOT NULL,
    componente VARCHAR(20) NOT NULL,
    cantidad INTEGER NOT NULL,
    prioridad VARCHAR(10) NOT NULL,
    estado VARCHAR(25) NOT NULL DEFAULT 'Pendiente',
    observaciones VARCHAR(300),

    CONSTRAINT uq_solicitud_codigo
        UNIQUE (codigo),

    CONSTRAINT chk_solicitud_tipo_sangre
        CHECK (tipo_sangre IN ('O-', 'O+', 'A-', 'A+', 'B-', 'B+', 'AB-', 'AB+')),

    CONSTRAINT chk_solicitud_componente
        CHECK (componente IN ('Glóbulos rojos', 'Plaquetas', 'Plasma')),

    CONSTRAINT chk_solicitud_cantidad
        CHECK (cantidad BETWEEN 1 AND 20),

    CONSTRAINT chk_solicitud_prioridad
        CHECK (prioridad IN ('Normal', 'Urgente')),

    CONSTRAINT chk_solicitud_estado
        CHECK (estado IN ('Pendiente', 'Atendida parcialmente', 'Atendida', 'Cancelada')),

    CONSTRAINT fk_solicitud_hospital
        FOREIGN KEY (id_hospital)
        REFERENCES banco_sangre.hospital(id_hospital)
);


CREATE TABLE IF NOT EXISTS banco_sangre.donacion (
    id_donacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL,
    id_donante BIGINT NOT NULL,
    id_campania BIGINT,
    fecha_donacion DATE NOT NULL,
    volumen_ml INTEGER NOT NULL,
    observaciones VARCHAR(300),

    CONSTRAINT uq_donacion_codigo
        UNIQUE (codigo),

    CONSTRAINT chk_donacion_volumen
        CHECK (volumen_ml BETWEEN 300 AND 500),

    CONSTRAINT fk_donacion_donante
        FOREIGN KEY (id_donante)
        REFERENCES banco_sangre.donante(id_donante),

    CONSTRAINT fk_donacion_campania
        FOREIGN KEY (id_campania)
        REFERENCES banco_sangre.campania(id_campania)
);


-- tipo_sangre se copia del donante para filtrar el inventario sin JOIN
-- y conservar el dato aunque el donante se corrija después.
CREATE TABLE IF NOT EXISTS banco_sangre.unidad_sanguinea (
    id_unidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(25) NOT NULL,
    id_donacion BIGINT NOT NULL,
    componente VARCHAR(20) NOT NULL,
    tipo_sangre VARCHAR(3) NOT NULL,
    fecha_extraccion DATE NOT NULL,
    fecha_vencimiento DATE NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'Disponible',
    id_solicitud BIGINT,

    CONSTRAINT uq_unidad_codigo
        UNIQUE (codigo),

    CONSTRAINT uq_unidad_donacion_componente
        UNIQUE (id_donacion, componente),

    CONSTRAINT chk_unidad_componente
        CHECK (componente IN ('Glóbulos rojos', 'Plaquetas', 'Plasma')),

    CONSTRAINT chk_unidad_tipo_sangre
        CHECK (tipo_sangre IN ('O-', 'O+', 'A-', 'A+', 'B-', 'B+', 'AB-', 'AB+')),

    CONSTRAINT chk_unidad_estado
        CHECK (estado IN ('Disponible', 'Reservada', 'Despachada', 'Vencida', 'Descartada')),

    CONSTRAINT chk_unidad_vencimiento
        CHECK (fecha_vencimiento > fecha_extraccion),

    CONSTRAINT fk_unidad_donacion
        FOREIGN KEY (id_donacion)
        REFERENCES banco_sangre.donacion(id_donacion),

    CONSTRAINT fk_unidad_solicitud
        FOREIGN KEY (id_solicitud)
        REFERENCES banco_sangre.solicitud(id_solicitud)
);
